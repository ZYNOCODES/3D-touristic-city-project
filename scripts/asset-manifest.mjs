// Builds the third-party asset manifest (docs/ASSETS.md + public/asset-credits.json)
// from public/assets-manifest.json, the Rocketbox people metadata and the vegetation atlases.
//   node scripts/asset-manifest.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const UA = { headers: { 'User-Agent': 'asset-manifest/1.0' } }
const am = JSON.parse(readFileSync('public/assets-manifest.json', 'utf8'))
const people = existsSync('public/models/people/people.json') ? JSON.parse(readFileSync('public/models/people/people.json', 'utf8')) : null
const veg = existsSync('public/models/vegetation/vegetation.json') ? JSON.parse(readFileSync('public/models/vegetation/vegetation.json', 'utf8')) : {}

async function phInfo(id) {
  try {
    const r = await fetch(`https://api.polyhaven.com/info/${id}`, UA)
    const j = await r.json()
    return Object.keys(j.authors ?? {}).join(', ')
  } catch {
    return 'Poly Haven'
  }
}

const rows = []
const MOD = {
  hdri: 'Normalised exposure, sun direction detected and aligned to the scene sun; blended per time of day.',
  texture: '1K maps; colour maps of plaster/stucco/linen dropped in favour of tinted base colours where noted.',
  model: 'Imported in Blender, placed & validated in generated interiors; textures capped at 1K, exported as WebP inside the interior GLBs.',
  tree: 'Rendered in Blender into 24-view impostor atlases (8 azimuths × 3 elevations), WebP.',
}
for (const [key, h] of Object.entries(am.hdri ?? {})) rows.push({ name: h.id, type: 'HDRI', source: 'Poly Haven', url: `https://polyhaven.com/a/${h.id}`, author: await phInfo(h.id), license: 'CC0 1.0', modifications: MOD.hdri, path: `public/${h.file}` })
for (const [key, t] of Object.entries(am.textures ?? {})) rows.push({ name: t.id, type: 'PBR texture', source: 'Poly Haven', url: `https://polyhaven.com/a/${t.id}`, author: await phInfo(t.id), license: 'CC0 1.0', modifications: MOD.texture, path: `public/textures/${key}/` })
const trees = new Set(['island_tree_01', 'island_tree_02', 'island_tree_03', 'pine_tree_01', 'fir_tree_01', 'jacaranda_tree', 'tree_small_02', 'shrub_01', 'shrub_02', 'shrub_04', 'searsia_lucida'])
for (const [id, path] of Object.entries(am.models ?? {})) {
  const tree = trees.has(id)
  rows.push({ name: id, type: tree ? '3D model (scanned plant)' : '3D model', source: 'Poly Haven', url: `https://polyhaven.com/a/${id}`, author: await phInfo(id), license: 'CC0 1.0', modifications: tree ? MOD.tree : MOD.model, path })
}
for (const [name, k] of Object.entries(am.khronos ?? {})) rows.push({ name, type: '3D model (product)', source: 'Khronos glTF-Sample-Assets', url: k.source, author: k.license.split('©')[1]?.trim() ?? 'Wayfair / Khronos', license: k.license.split(' ')[0], modifications: 'Scaled to real-world size, placed & validated in the apartment / villa interiors; textures re-encoded (8-bit WebP, ≤1K).', path: k.path })
if (people) {
  for (const a of people.avatars) rows.push({ name: a.id, type: 'Rigged human (81-bone Biped)', source: 'Microsoft Rocketbox Avatar Library', url: 'https://github.com/microsoft/Microsoft-Rocketbox', author: 'Microsoft / Rocketbox Studios', license: 'MIT', modifications: 'FBX → GLB in Blender, materials rebuilt from 2K TGA maps (1K/512 WebP), hair/eyelash alpha cards.', path: a.file })
  rows.push({ name: `${Object.keys(people.clips).length} motion-capture clips`, type: 'Animation', source: 'Microsoft Rocketbox Avatar Library', url: 'https://github.com/microsoft/Microsoft-Rocketbox/tree/master/Assets/Animations', author: 'Microsoft / Rocketbox Studios', license: 'MIT', modifications: 'Scale & finger/face channels stripped, long idles trimmed to 16 s, root motion removed (speed measured for foot-locked walking).', path: 'public/models/people/anims/' })
}
for (const [k, v] of Object.entries(veg)) {
  if (/cypress|palm|shrub|pampas|lavender/.test(k)) rows.push({ name: k, type: 'Procedural plant (impostor)', source: 'Generated by blender/build_vegetation.py', url: '—', author: 'This project', license: 'Project-owned', modifications: k.startsWith('cypress') ? 'Cards use the CC0 Poly Haven fir_tree_01 twig texture.' : 'Fully procedural geometry & materials.', path: v.atlas })
}
rows.push({ name: 'Map tiles', type: 'Basemap', source: 'CARTO / OpenStreetMap', url: 'https://carto.com/attributions', author: 'OpenStreetMap contributors, CARTO', license: 'ODbL (data) / CARTO terms', modifications: 'None — attribution shown on the map. Use your own tile provider in production.', path: 'runtime' })

writeFileSync('public/asset-credits.json', JSON.stringify(rows, null, 1))
const md = [
  '# Third-party assets & licences',
  '',
  'Generated by `node scripts/asset-manifest.mjs`. Every asset below permits commercial use',
  '(CC0, CC-BY 4.0 with attribution, or MIT). CC-BY items require the attribution shown here to',
  'appear in the product credits (the app exposes it in `public/asset-credits.json`).',
  '',
  '| Asset | Type | Source | Author | Licence | Modifications | Local path |',
  '|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.url !== '—' && r.url !== 'runtime' ? `[${r.name}](${r.url})` : r.name} | ${r.type} | ${r.source} | ${r.author} | ${r.license} | ${r.modifications} | \`${r.path}\` |`),
  '',
  'Architecture (residence, villas, amenities), interiors, furniture and the people/vegetation',
  'pipelines are generated by the scripts in `blender/` and are owned by this project.',
  '',
].join('\n')
writeFileSync('docs/ASSETS.md', md)
console.log(`${rows.length} assets documented → docs/ASSETS.md, public/asset-credits.json`)
